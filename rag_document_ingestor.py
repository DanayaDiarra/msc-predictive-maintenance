# ── Subsystem keyword detector ────────────────────────────────────────────────
SUBSYSTEM_KEYWORDS = {
    "power_subsystem":       ["rectifier","voltage","battery","pwr-","mains","dc bus","mcb","BBU-00"],
    "thermal_management":    ["cooling","fan","temperature","COOL-","thermal","heat exchanger","HVAC"],
    "rf_antenna":            ["vswr","antenna","RF-","feeder","PIM","connector","PA module","LNA"],
    "backhaul_connectivity": ["backhaul","latency","fibre","microwave","BKH-","OTDR","packet loss"],
    "baseband_processing":   ["BBU","baseband","CPU","BB-","software","upgrade","memory","FPGA"],
}
DOCTYPE_KEYWORDS = {
    "sop":        ["procedure","step","SOP","instruction","how to","process"],
    "manual":     ["specification","manual","datasheet","technical note","nominal","threshold"],
    "alarm_dict": ["alarm","alert","severity","probable cause","action","clear","code"],
    "ticket":     ["incident","INC-","resolution","root cause","work performed","closed"],
    "spec":       ["3GPP","ITU-T","ETSI","standard","recommendation","TS ","TR "],
    "fmea":       ["FMEA","failure mode","RPN","occurrence","severity","detection"],
    "tree":       ["decision","flowchart","triage","Q1","Q2","YES","NO","→"],
}

def detect_subsystem(text: str) -> str:
    text_lo = text.lower()
    scores = {sub: sum(1 for kw in kws if kw.lower() in text_lo)
              for sub, kws in SUBSYSTEM_KEYWORDS.items()}
    best = max(scores, key=scores.get)
    return best if scores[best] > 0 else "general"

def detect_doctype(text: str, filename: str = "") -> str:
    combined = (text + " " + filename).lower()
    scores = {dt: sum(1 for kw in kws if kw.lower() in combined)
              for dt, kws in DOCTYPE_KEYWORDS.items()}
    best = max(scores, key=scores.get)
    return best if scores[best] > 0 else "manual"

def make_chunk_id(text: str) -> str:
    return hashlib.md5(text.encode()).hexdigest()[:12]

