"""
rag_document_ingestor.py — Real Document Ingestion for FluxAgent RAG Corpus
=============================================================================
Thesis: Agentic AI for Predictive Maintenance | Danaya Diarra | GSOM SPBU | 2026

PURPOSE
-------
Ingests REAL maintenance documents into the RAG corpus, replacing the synthetic
knowledge base generated by rag_corpus_builder.py with actual vendor manuals,
operator SOPs, alarm guides, maintenance tickets, and field reports.

This is the production path for real deployment:

  REAL DOCUMENTS → rag_document_ingestor.py → data/rag_corpus/corpus.json
                                             → data/rag_index/ (TF-IDF + SVD)
                                             → streamlit_pdm.py (DiagnosticAgent)

SUPPORTED INPUT FORMATS
-----------------------
  • PDF         — vendor manuals, 3GPP specs, ITU-T recommendations
  • Word (.docx) — internal SOPs, maintenance procedures, field reports
  • HTML        — scraped vendor knowledge bases, online documentation
  • CSV / JSON  — historical ticket exports from OSS/BSS (Nokia NetAct, Ericsson OSS)
  • Plain text  — alarm dictionaries, threshold tables, engineering notes
  • Excel (.xlsx) — FMEA tables, KPI threshold sheets, spare parts catalogs

CHUNKING STRATEGY
-----------------
  • Target chunk size: 400–600 tokens (~350–500 words)
  • Overlap: 80 tokens (preserves context at boundaries)
  • Semantic splitting: respects paragraph/section boundaries (never mid-sentence)
  • Metadata tagging: auto-detect doc_type, subsystem, alarm codes from content

USAGE
-----
  # Ingest a single PDF manual
  python rag_document_ingestor.py --file docs/ericsson_rbs6601_maintenance.pdf

  # Ingest all documents in a folder
  python rag_document_ingestor.py --dir docs/vendor_manuals/

  # Ingest from a ticket export CSV (Nokia NetAct, Ericsson OSS)
  python rag_document_ingestor.py --tickets exports/maintenance_tickets_2024.csv

  # Merge with synthetic corpus (add real docs without losing baseline)
  python rag_document_ingestor.py --dir docs/ --merge

  # Full rebuild: clear synthetic corpus, ingest all real docs
  python rag_document_ingestor.py --dir docs/ --rebuild

  # Preview what would be ingested (dry run)
  python rag_document_ingestor.py --dir docs/ --dry-run

INTEGRATION WITH FluxAgent
--------------------------
After ingestion, the RAG index is automatically rebuilt and the DiagnosticAgent
will use real documents on the next query — no restart needed.

    from rag_document_ingestor import DocumentIngestor
    ingestor = DocumentIngestor()
    ingestor.ingest_file("path/to/manual.pdf")
    ingestor.rebuild_index()  # updates data/rag_index/ in place
"""

